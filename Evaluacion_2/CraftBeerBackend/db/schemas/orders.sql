WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE ZONA_DESPACHO (
  ID_ZONA NUMBER PRIMARY KEY, NOMBRE VARCHAR2(60) NOT NULL, RADIO_GRATIS_KM NUMBER NOT NULL,
  TARIFA_FUERA NUMBER(8) NOT NULL, MONTO_ENVIO_GRATIS NUMBER(8) NOT NULL);
CREATE TABLE PEDIDO (
  ID_PEDIDO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  REF VARCHAR2(40) NOT NULL UNIQUE,
  ID_CLIENTE NUMBER NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE_PAGO' NOT NULL
    CHECK (ESTADO IN ('PENDIENTE_PAGO','PAGADO','EN_PREPARACION','EN_DESPACHO','ENTREGADO','ANULADO')),
  SUBTOTAL NUMBER(10) NOT NULL, COSTO_ENVIO NUMBER(8) NOT NULL, TOTAL NUMBER(10) NOT NULL,
  DIRECCION_ENTREGA VARCHAR2(200) NOT NULL,
  DISTANCIA_KM NUMBER(5,1),
  MOTIVO_ANULACION VARCHAR2(200),
  CREADO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  EXPIRA TIMESTAMP NOT NULL);
CREATE TABLE DETALLE_PEDIDO (
  ID_DETALLE NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_PEDIDO NUMBER NOT NULL REFERENCES PEDIDO(ID_PEDIDO),
  ID_PRODUCTO NUMBER NOT NULL,
  NOMBRE_PRODUCTO VARCHAR2(100) NOT NULL,
  PRECIO_UNITARIO NUMBER(10) NOT NULL,
  CANTIDAD NUMBER NOT NULL CHECK (CANTIDAD > 0));
CREATE INDEX IX_PEDIDO_CLI ON PEDIDO(ID_CLIENTE);

CREATE OR REPLACE PROCEDURE SP_CREAR_PEDIDO(
  p_ref VARCHAR2, p_cliente NUMBER, p_dir VARCHAR2, p_km NUMBER, p_subtotal NUMBER,
  o_id OUT NUMBER, o_envio OUT NUMBER, o_total OUT NUMBER) AS
  v_z ZONA_DESPACHO%ROWTYPE;
BEGIN
  SELECT * INTO v_z FROM ZONA_DESPACHO WHERE ID_ZONA=1;
  o_envio := CASE WHEN p_km <= v_z.RADIO_GRATIS_KM OR p_subtotal >= v_z.MONTO_ENVIO_GRATIS THEN 0 ELSE v_z.TARIFA_FUERA END;
  o_total := p_subtotal + o_envio;
  INSERT INTO PEDIDO(REF, ID_CLIENTE, SUBTOTAL, COSTO_ENVIO, TOTAL, DIRECCION_ENTREGA, DISTANCIA_KM, EXPIRA)
  VALUES (p_ref, p_cliente, p_subtotal, o_envio, o_total, p_dir, p_km, SYSTIMESTAMP + INTERVAL '15' MINUTE)
  RETURNING ID_PEDIDO INTO o_id;
END;
/
CREATE OR REPLACE PROCEDURE SP_ANULAR_PEDIDO(p_id NUMBER, p_motivo VARCHAR2, o_ref OUT VARCHAR2) AS
  v_est VARCHAR2(20);
BEGIN
  SELECT ESTADO, REF INTO v_est, o_ref FROM PEDIDO WHERE ID_PEDIDO=p_id FOR UPDATE;
  IF v_est IN ('ENTREGADO','ANULADO','EN_DESPACHO') THEN
    RAISE_APPLICATION_ERROR(-20010, 'ESTADO_NO_ANULABLE');
  END IF;
  UPDATE PEDIDO SET ESTADO='ANULADO', MOTIVO_ANULACION=p_motivo WHERE ID_PEDIDO=p_id;
  COMMIT;
END;
/
CREATE OR REPLACE PROCEDURE SP_EXPIRAR_PEDIDOS AS
BEGIN
  UPDATE PEDIDO SET ESTADO='ANULADO', MOTIVO_ANULACION='EXPIRADO_SIN_PAGO'
  WHERE ESTADO='PENDIENTE_PAGO' AND EXPIRA < SYSTIMESTAMP;
  COMMIT;
END;
/
