WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE ORDEN_DESPACHO (
  ID_ORDEN NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_PEDIDO NUMBER NOT NULL UNIQUE, ID_CLIENTE NUMBER NOT NULL,
  DIRECCION VARCHAR2(200) NOT NULL, TELEFONO VARCHAR2(20),
  ESTADO VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL
    CHECK (ESTADO IN ('PENDIENTE','EN_PREPARACION','EN_RUTA','ENTREGADO','FALLIDO')),
  EDAD_VERIFICADA NUMBER(1) DEFAULT 0 NOT NULL,
  ID_CHOFER NUMBER, CREADO TIMESTAMP DEFAULT SYSTIMESTAMP, ACTUALIZADO TIMESTAMP);
CREATE TABLE CHOFER (ID_CHOFER NUMBER PRIMARY KEY, NOMBRE VARCHAR2(80) NOT NULL, ACTIVO NUMBER(1) DEFAULT 1);
CREATE OR REPLACE PROCEDURE SP_CREAR_ORDEN_DESPACHO(p_pedido NUMBER, p_cli NUMBER, p_dir VARCHAR2, p_tel VARCHAR2, o_id OUT NUMBER) AS
BEGIN
  BEGIN
    INSERT INTO ORDEN_DESPACHO(ID_PEDIDO, ID_CLIENTE, DIRECCION, TELEFONO) VALUES (p_pedido, p_cli, p_dir, p_tel)
      RETURNING ID_ORDEN INTO o_id;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
    SELECT ID_ORDEN INTO o_id FROM ORDEN_DESPACHO WHERE ID_PEDIDO=p_pedido;
  END;
  COMMIT;
END;
