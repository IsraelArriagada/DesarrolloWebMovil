WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE NOTIFICACION_COLA (
  ID_NOTIF NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TIPO VARCHAR2(30) NOT NULL, DESTINATARIO VARCHAR2(120) NOT NULL,
  ASUNTO VARCHAR2(150), CUERPO CLOB,
  ESTADO VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL CHECK (ESTADO IN ('PENDIENTE','ENVIADA','FALLIDA')),
  INTENTOS NUMBER DEFAULT 0, CREADO TIMESTAMP DEFAULT SYSTIMESTAMP, ENVIADO TIMESTAMP);
CREATE OR REPLACE PROCEDURE SP_ENCOLAR_NOTIFICACION(p_tipo VARCHAR2, p_dest VARCHAR2, p_asunto VARCHAR2, p_cuerpo CLOB, o_id OUT NUMBER) AS
BEGIN
  INSERT INTO NOTIFICACION_COLA(TIPO, DESTINATARIO, ASUNTO, CUERPO) VALUES (p_tipo, p_dest, p_asunto, p_cuerpo)
    RETURNING ID_NOTIF INTO o_id;
  COMMIT;
END;
/
CREATE OR REPLACE PROCEDURE SP_MARCAR_ENVIADA(p_id NUMBER, p_ok NUMBER) AS
BEGIN
  UPDATE NOTIFICACION_COLA SET INTENTOS=INTENTOS+1,
    ESTADO = CASE WHEN p_ok=1 THEN 'ENVIADA' WHEN INTENTOS+1>=3 THEN 'FALLIDA' ELSE 'PENDIENTE' END,
    ENVIADO = CASE WHEN p_ok=1 THEN SYSTIMESTAMP ELSE ENVIADO END
  WHERE ID_NOTIF=p_id;
  COMMIT;
END;
/
EXIT;
