WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE PAGO (
  ID_PAGO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_PEDIDO NUMBER NOT NULL, REF_PEDIDO VARCHAR2(40) NOT NULL,
  MONTO NUMBER(10) NOT NULL, METODO VARCHAR2(15) NOT NULL,
  ESTADO VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL CHECK (ESTADO IN ('PENDIENTE','APROBADO','RECHAZADO')),
  ID_TRANSACCION_EXT VARCHAR2(60) UNIQUE,
  CREADO TIMESTAMP DEFAULT SYSTIMESTAMP);
CREATE UNIQUE INDEX UX_PAGO_APROBADO ON PAGO(CASE WHEN ESTADO='APROBADO' THEN ID_PEDIDO END);
CREATE TABLE VENTA (
  ID_VENTA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_PEDIDO NUMBER NOT NULL UNIQUE, ID_PAGO NUMBER NOT NULL REFERENCES PAGO(ID_PAGO),
  TOTAL NUMBER(10) NOT NULL, FECHA TIMESTAMP DEFAULT SYSTIMESTAMP);
CREATE TABLE BOLETA (
  ID_BOLETA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_VENTA NUMBER NOT NULL REFERENCES VENTA(ID_VENTA),
  ID_PEDIDO NUMBER NOT NULL UNIQUE, ID_CLIENTE NUMBER NOT NULL,
  NUMERO VARCHAR2(20) NOT NULL UNIQUE, TOTAL NUMBER(10) NOT NULL,
  DETALLE_JSON CLOB, EMITIDA TIMESTAMP DEFAULT SYSTIMESTAMP);
CREATE SEQUENCE SEQ_BOLETA START WITH 1000;

-- Idempotente: si ya existe pago aprobado para el pedido o la transacción, devuelve o_dup=1
CREATE OR REPLACE PROCEDURE SP_CONFIRMAR_PAGO(
  p_pedido NUMBER, p_ref VARCHAR2, p_monto NUMBER, p_metodo VARCHAR2, p_tx VARCHAR2,
  p_cliente NUMBER, p_detalle CLOB, o_dup OUT NUMBER, o_boleta OUT VARCHAR2) AS
  v_pago NUMBER; v_venta NUMBER; v_n NUMBER;
BEGIN
  o_dup := 0;
  SELECT COUNT(*) INTO v_n FROM PAGO WHERE ID_TRANSACCION_EXT = p_tx OR (ID_PEDIDO=p_pedido AND ESTADO='APROBADO');
  IF v_n > 0 THEN
    o_dup := 1;
    SELECT NUMERO INTO o_boleta FROM BOLETA WHERE ID_PEDIDO=p_pedido;
    RETURN;
  END IF;
  INSERT INTO PAGO(ID_PEDIDO, REF_PEDIDO, MONTO, METODO, ESTADO, ID_TRANSACCION_EXT)
    VALUES (p_pedido, p_ref, p_monto, p_metodo, 'APROBADO', p_tx) RETURNING ID_PAGO INTO v_pago;
  INSERT INTO VENTA(ID_PEDIDO, ID_PAGO, TOTAL) VALUES (p_pedido, v_pago, p_monto) RETURNING ID_VENTA INTO v_venta;
  o_boleta := 'B-' || LPAD(SEQ_BOLETA.NEXTVAL, 8, '0');
  INSERT INTO BOLETA(ID_VENTA, ID_PEDIDO, ID_CLIENTE, NUMERO, TOTAL, DETALLE_JSON)
    VALUES (v_venta, p_pedido, p_cliente, o_boleta, p_monto, p_detalle);
  COMMIT;
EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
  ROLLBACK; o_dup := 1;
  SELECT NUMERO INTO o_boleta FROM BOLETA WHERE ID_PEDIDO=p_pedido;
END;
/
CREATE OR REPLACE PROCEDURE SP_REPORTE_VENTAS(p_desde DATE, p_hasta DATE, o_cur OUT SYS_REFCURSOR) AS
BEGIN
  OPEN o_cur FOR SELECT TRUNC(FECHA) DIA, COUNT(*) CANTIDAD, SUM(TOTAL) TOTAL
    FROM VENTA WHERE FECHA >= p_desde AND FECHA < p_hasta + 1 GROUP BY TRUNC(FECHA) ORDER BY 1;
END;
/
EXIT;
