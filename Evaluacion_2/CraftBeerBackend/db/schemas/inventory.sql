WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE PRODUCTO (
  ID_PRODUCTO NUMBER PRIMARY KEY,
  NOMBRE VARCHAR2(100) NOT NULL,
  CATEGORIA VARCHAR2(30) NOT NULL,
  PRECIO NUMBER(10) NOT NULL CHECK (PRECIO > 0),
  STOCK NUMBER NOT NULL CHECK (STOCK >= 0),
  DISPONIBLE NUMBER(1) DEFAULT 1 NOT NULL
);
CREATE TABLE RESERVA_STOCK (
  ID_RESERVA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_PEDIDO_REF VARCHAR2(40) NOT NULL,
  ID_PRODUCTO NUMBER NOT NULL REFERENCES PRODUCTO(ID_PRODUCTO),
  CANTIDAD NUMBER NOT NULL CHECK (CANTIDAD > 0),
  ESTADO VARCHAR2(12) DEFAULT 'ACTIVA' NOT NULL CHECK (ESTADO IN ('ACTIVA','CONFIRMADA','LIBERADA')),
  EXPIRA TIMESTAMP NOT NULL
);
CREATE INDEX IX_RESERVA_REF ON RESERVA_STOCK(ID_PEDIDO_REF);

-- Reserva atómica de todo el pedido; OUT o_error vacío si OK
CREATE OR REPLACE PROCEDURE SP_RESERVAR_STOCK(p_ref VARCHAR2, p_ids VARCHAR2, p_cants VARCHAR2, o_error OUT VARCHAR2) AS
  v_stock NUMBER; v_disp NUMBER; v_id NUMBER; v_c NUMBER;
  TYPE t IS TABLE OF VARCHAR2(30);
  ids t; cs t;
  FUNCTION split(s VARCHAR2) RETURN t IS r t := t(); p NUMBER := 1; q NUMBER;
  BEGIN
    LOOP
      q := INSTR(s, ',', p);
      r.EXTEND;
      IF q = 0 THEN r(r.COUNT) := SUBSTR(s, p); EXIT; END IF;
      r(r.COUNT) := SUBSTR(s, p, q-p); p := q+1;
    END LOOP;
    RETURN r;
  END;
BEGIN
  o_error := NULL;
  ids := split(p_ids); cs := split(p_cants);
  FOR i IN 1..ids.COUNT LOOP
    v_id := TO_NUMBER(ids(i)); v_c := TO_NUMBER(cs(i));
    BEGIN
      SELECT STOCK, DISPONIBLE INTO v_stock, v_disp FROM PRODUCTO WHERE ID_PRODUCTO=v_id FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      ROLLBACK; o_error := 'PRODUCTO_INEXISTENTE:' || v_id; RETURN;
    END;
    IF v_disp = 0 OR v_stock < v_c THEN
      ROLLBACK; o_error := 'SIN_STOCK:' || v_id; RETURN;
    END IF;
    UPDATE PRODUCTO SET STOCK = STOCK - v_c WHERE ID_PRODUCTO=v_id;
    INSERT INTO RESERVA_STOCK(ID_PEDIDO_REF, ID_PRODUCTO, CANTIDAD, EXPIRA)
      VALUES (p_ref, v_id, v_c, SYSTIMESTAMP + INTERVAL '15' MINUTE);
  END LOOP;
  COMMIT;
END;
/
CREATE OR REPLACE PROCEDURE SP_LIBERAR_RESERVA(p_ref VARCHAR2) AS
BEGIN
  FOR r IN (SELECT ID_RESERVA, ID_PRODUCTO, CANTIDAD FROM RESERVA_STOCK
            WHERE ID_PEDIDO_REF=p_ref AND ESTADO='ACTIVA' FOR UPDATE) LOOP
    UPDATE PRODUCTO SET STOCK = STOCK + r.CANTIDAD WHERE ID_PRODUCTO=r.ID_PRODUCTO;
    UPDATE RESERVA_STOCK SET ESTADO='LIBERADA' WHERE ID_RESERVA=r.ID_RESERVA;
  END LOOP;
  COMMIT;
END;
/
CREATE OR REPLACE PROCEDURE SP_CONFIRMAR_RESERVA(p_ref VARCHAR2) AS
BEGIN
  UPDATE RESERVA_STOCK SET ESTADO='CONFIRMADA' WHERE ID_PEDIDO_REF=p_ref AND ESTADO='ACTIVA';
  COMMIT;
END;
/
CREATE OR REPLACE PROCEDURE SP_LIBERAR_RESERVAS_VENCIDAS AS
BEGIN
  FOR r IN (SELECT ID_RESERVA, ID_PRODUCTO, CANTIDAD FROM RESERVA_STOCK
            WHERE ESTADO='ACTIVA' AND EXPIRA < SYSTIMESTAMP FOR UPDATE SKIP LOCKED) LOOP
    UPDATE PRODUCTO SET STOCK = STOCK + r.CANTIDAD WHERE ID_PRODUCTO=r.ID_PRODUCTO;
    UPDATE RESERVA_STOCK SET ESTADO='LIBERADA' WHERE ID_RESERVA=r.ID_RESERVA;
  END LOOP;
  COMMIT;
END;
/
