WHENEVER SQLERROR EXIT FAILURE
CREATE TABLE USUARIO (
  ID_USUARIO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CORREO VARCHAR2(120) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(100) NOT NULL,
  ROL VARCHAR2(10) NOT NULL CHECK (ROL IN ('ADMIN','CLIENTE','CAJERO','DESPACHO','DUENO')),
  INTENTOS_FALLIDOS NUMBER DEFAULT 0 NOT NULL,
  BLOQUEADO_HASTA TIMESTAMP,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL
);
CREATE TABLE CLIENTE (
  ID_CLIENTE NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_USUARIO NUMBER NOT NULL UNIQUE REFERENCES USUARIO(ID_USUARIO),
  NOMBRE VARCHAR2(100) NOT NULL,
  TELEFONO VARCHAR2(20),
  DIRECCION VARCHAR2(200),
  FECHA_NACIMIENTO DATE NOT NULL,
  ACEPTA_TERMINOS NUMBER(1) NOT NULL CHECK (ACEPTA_TERMINOS=1),
  FECHA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_CLIENTE(
  p_correo VARCHAR2, p_hash VARCHAR2, p_nombre VARCHAR2, p_tel VARCHAR2, p_dir VARCHAR2,
  p_nac DATE, p_terminos NUMBER, o_id_usuario OUT NUMBER, o_id_cliente OUT NUMBER) AS
BEGIN
  IF MONTHS_BETWEEN(TRUNC(SYSDATE), p_nac) < 216 THEN
    RAISE_APPLICATION_ERROR(-20001, 'MENOR_DE_EDAD');
  END IF;
  INSERT INTO USUARIO(CORREO, PASSWORD_HASH, ROL) VALUES (LOWER(p_correo), p_hash, 'CLIENTE')
    RETURNING ID_USUARIO INTO o_id_usuario;
  INSERT INTO CLIENTE(ID_USUARIO, NOMBRE, TELEFONO, DIRECCION, FECHA_NACIMIENTO, ACEPTA_TERMINOS)
    VALUES (o_id_usuario, p_nombre, p_tel, p_dir, p_nac, p_terminos)
    RETURNING ID_CLIENTE INTO o_id_cliente;
EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
  RAISE_APPLICATION_ERROR(-20002, 'CORREO_DUPLICADO');
END;
/
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_INTENTO_LOGIN(p_correo VARCHAR2, p_ok NUMBER) AS
BEGIN
  IF p_ok = 1 THEN
    UPDATE USUARIO SET INTENTOS_FALLIDOS=0, BLOQUEADO_HASTA=NULL WHERE CORREO=LOWER(p_correo);
  ELSE
    UPDATE USUARIO SET INTENTOS_FALLIDOS = INTENTOS_FALLIDOS+1,
      BLOQUEADO_HASTA = CASE WHEN INTENTOS_FALLIDOS+1 >= 5 THEN SYSTIMESTAMP + INTERVAL '15' MINUTE ELSE BLOQUEADO_HASTA END
    WHERE CORREO=LOWER(p_correo);
  END IF;
  COMMIT;
END;
